/**
 * REFS neighbourhood probabilities. Each is one `.idx` component picked out by its threshold column,
 * so a probability field is an ordinary scalar component whose value is the percent chance the
 * threshold is reached somewhere in the neighbourhood. The thresholds are NOAA's, not ours:
 * `tests/models/models-catalog.test.mjs` fails if one is renamed or dropped.
 *
 * All of them live behind the `prob` product. The `mean` and `sprd` objects do not carry
 * them. Probability fields share the categories of the corresponding weather fields.
 */
const probabilityPane = (variable: string, level: string): ModelPaneId => {
    if (level === '850 mb') return '850';
    if (level === '250 mb') return '250';
    if (['REFC', 'CAPE', 'CIN', 'HLCY', 'MAXREF', 'REFD', 'LTNG'].includes(variable)) return 'severe';
    if (['ASNOW', 'FRZR', 'CSNOW', 'CICEP', 'CFRZR'].includes(variable)) return 'winter';
    if (['APCP', 'CRAIN'].includes(variable)) return 'precip';
    return 'surface';
};
const prob = (
    suffix: string,
    label: string,
    shortLabel: string,
    variable: string,
    level: string,
    timing: ModelTiming,
    threshold: string,
    units: string,
    quantity: ModelQuantity,
    scale?: number,
) =>
    defineField({
        id: `REFS_PROB_${suffix}`,
        product: 'prob',
        label: `Probability of ${label}`,
        shortLabel,
        pane: probabilityPane(variable, level),
        kind: 'scalar',
        units,
        quantity,
        // `threshold` selects this component from the many that share a variable, level and forecast.
        inputs: [
            sfc(variable, level, {
                timing,
                threshold,
                exact: true,
                transform: scale === undefined ? undefined : { scale },
            }) as ModelSelector,
        ],
        colormap: { name: 'MRMS_Probability', range: [0, 100] },
    });

